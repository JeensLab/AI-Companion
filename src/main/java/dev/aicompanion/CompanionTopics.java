    private static void add(List<Topic> all, String category, String... texts) {
        for (String text : texts) all.add(new Topic("bank:" + CompanionConversation.normalize(text), category, text));
    }
    /** A topic he made of a talk himself. */
    public static Topic own(String text) { return new Topic("own:" + CompanionConversation.normalize(text), "own", text); }
    /** The bank topic with this key, or null for a key that is no longer in the bank. */
    public static Topic bank(String key) { return ALL.stream().filter(topic -> topic.key().equals(key)).findFirst().orElse(null); }
    /** The words of a raised topic, for the next condensing; empty for a key that is no longer in the bank. */
    public static String text(String key) {
        if (key.startsWith("own:")) return key.substring(4);
        Topic topic = bank(key);
        return topic == null ? "" : topic.text();
    }
    /** The same words as the topic with this key, in another order or with other punctuation. */
    public static boolean repeats(String key, String text) {
        return CompanionConversation.similar(key.substring(key.indexOf(':') + 1), CompanionConversation.normalize(text));
    }
    /** A line he can say as it is: Russian, short, one question at most, no links, markup or game IDs, nothing banned. */
    public static boolean speakable(String text) {
        return text != null && text.length() >= 8 && text.length() <= 140 && allowed(text) && text.chars().filter(c -> c == '?').count() <= 1
                && text.matches("(?s).*[а-яА-ЯёЁ].*") && !text.matches("(?is).*(https?:|www\\.|minecraft:|[\\[\\]{}<>]).*");
    }
    private static boolean allowed(String text) { return !BANNED.matcher(text.toLowerCase(Locale.ROOT).replace('ё', 'е')).find(); }
