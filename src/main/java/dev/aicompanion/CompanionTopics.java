    private static void add(List<CompanionSoul.Topic> all, String category, String... texts) {
        for (String text : texts) all.add(new CompanionSoul.Topic("bank:" + CompanionConversation.normalize(text), category, text));
    }
    /** The words of a raised topic, for the analysis; empty for a key that is no longer in the bank. */
    static String text(String key) {
        if (key.startsWith("own:")) return key.substring(4);
        return ALL.stream().filter(topic -> topic.key().equals(key)).map(CompanionSoul.Topic::text).findFirst().orElse("");
    }
